// Generates src/schema.auto.ts from Discord's official OpenAPI spec,
// trimmed down to the endpoints an OAuth2 app actually calls.
import openapiTS, { astToString } from "openapi-typescript";

const SPEC_URL =
  "https://raw.githubusercontent.com/discord/discord-api-spec/main/specs/openapi.json";

const KEEP: Record<string, string[]> = {
  "/oauth2/@me": ["get"],
  "/users/@me": ["get"],
  "/users/@me/guilds": ["get"],
  "/users/@me/guilds/{guild_id}/member": ["get"],
  "/users/@me/connections": ["get"],
  "/guilds/{guild_id}/members/{user_id}": ["put"],
};

const spec = await (await fetch(SPEC_URL)).json();

spec.paths = Object.fromEntries(
  Object.entries(KEEP).map(([path, methods]) => {
    const item = spec.paths[path];
    if (!item) throw new Error(`${path} is missing from the spec`);
    return [path, Object.fromEntries(["parameters", ...methods].map((m) => [m, item[m]]))];
  }),
);

// Keep only components reachable from the kept paths.
const reachable = new Set<string>();
const walk = (node: unknown): void => {
  if (Array.isArray(node)) return node.forEach(walk);
  if (!node || typeof node !== "object") return;
  for (const [key, value] of Object.entries(node)) {
    if (key === "$ref" && typeof value === "string" && !reachable.has(value)) {
      reachable.add(value);
      const [, , section, name] = value.split("/");
      walk(spec.components[section!][name!]);
    } else walk(value);
  }
};
walk(spec.paths);

for (const [section, entries] of Object.entries<Record<string, unknown>>(spec.components)) {
  if (section === "securitySchemes") continue;
  spec.components[section] = Object.fromEntries(
    Object.entries(entries).filter(([name]) => reachable.has(`#/components/${section}/${name}`)),
  );
}

const scopes = Object.keys(spec.components.securitySchemes.OAuth2.flows.authorizationCode.scopes);

const output = [
  `// Generated by scripts/generate.ts from ${SPEC_URL} (v${spec.info.version}). Do not edit.`,
  astToString(await openapiTS(spec)),
  `export type OAuth2Scope = ${scopes.map((s) => JSON.stringify(s)).join(" | ")};`,
].join("\n");

await Bun.write(new URL("../src/schema.auto.ts", import.meta.url), output);
console.log(`schema.auto.ts: ${reachable.size} components, ${scopes.length} scopes`);
